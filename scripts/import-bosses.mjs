// Generates src/bossesImported.ts from the RuneScape Wiki "Bosses" page and each boss page.
// Run locally: node --experimental-strip-types scripts/import-bosses.mjs
// Prints one review line per boss: its derived collection log items. Corrections go in
// src/bossGuides.ts (uniques.add / uniques.remove) so they survive re-imports.
import { writeFileSync } from "node:fs";
import { BOSS_GUIDES } from "../src/bossGuides.ts";
import { QUESTS } from "../src/data.ts";
import {
  deriveUniques,
  hasStrategy,
  parseAchievements,
  parseBossesTable,
  parseDrops,
  parseInfobox,
} from "./bossWikitext.mjs";
import { createWikiApi, fileName, nameKey, slug } from "./wikiApi.mjs";

const USER_AGENT = "RS3 Compass boss import (https://github.com/AlexMollard/RS3-Compass)";
const { categoryMembers, pageContents, servedFiles } = createWikiApi(USER_AGENT);
const OUT = new URL("../src/bossesImported.ts", import.meta.url);

// Quest names match by nameKey, with and without a " (quest)" disambiguator.
const noSuffix = (key) => key.replace(/\s*\(quest\)$/, "");
const known = new Map();
for (const q of QUESTS)
  for (const key of [nameKey(q.name), nameKey(q.wiki), q.id]) {
    known.set(key, q.id);
    known.set(noSuffix(key), q.id);
  }

const rows = parseBossesTable((await pageContents(["Bosses"])).get("Bosses"));
const f2pCategory = new Set((await categoryMembers("Free-to-play bosses")).map(nameKey));
const contents = await pageContents(rows.map((r) => r.name));
// "<name>.png" first; group fights (The Barrows Brothers) and odd casing (Giant mole.png) fall back to the Bosses table's picture.
const imageOf = (r) => [`${r.name}.png`, r.image].filter(Boolean).map(fileName);
const images = await servedFiles(rows.flatMap(imageOf));

// A page with several infobox versions (Rasial: "members1 = No", "members2 = Yes") is F2P only if every one says No.
const infoboxF2p = (page) => {
  const values = [...page.matchAll(/^\s*\|\s*members\d*\s*=\s*(\w+)/gim)].map((m) => m[1].toLowerCase());
  return values.length > 0 && values.every((v) => v === "no");
};

const records = [];
const review = [];
for (const row of rows) {
  const page = contents.get(row.name);
  if (!page) throw new Error(`No Wiki page for ${row.name}`);
  const infobox = parseInfobox(page);
  const drops = parseDrops(page);
  const uniques = deriveUniques(row.signature, drops);
  review.push(`${row.name}: ${uniques.join(", ")}`);
  const image = imageOf(row).map((f) => images.get(f)).find(Boolean);
  records.push({
    id: slug(row.name),
    name: row.name,
    wiki: row.name.replaceAll(" ", "_"),
    ...(image ? { image } : {}),
    level: row.level,
    tier: row.tier,
    team: row.team,
    members: !(f2pCategory.has(nameKey(row.name)) || infoboxF2p(page)),
    ...(infobox.lifepoints ? { lifepoints: infobox.lifepoints } : {}),
    ...(infobox.weakness ? { weakness: infobox.weakness } : {}),
    requirements: row.requirements.map((r) => {
      if (r.kind !== "quest") return r;
      const quest = known.get(nameKey(r.name)) ?? known.get(noSuffix(nameKey(r.name)));
      return quest ? { kind: "quest", quest } : { kind: "text", text: r.name };
    }),
    drops,
    uniques,
    achievements: parseAchievements(page),
    ...(hasStrategy(page) ? { strategyPage: `${row.name}/Strategies` } : {}),
    ...(row.releaseDate ? { releaseDate: row.releaseDate } : {}),
  });
}

const marked = records.filter((r) => /[|}]/.test(r.releaseDate ?? ""));
if (marked.length) throw new Error(`Wikitext markup in releaseDate: ${marked.map((r) => r.name).join(", ")}`);
const missing =records.filter((r) => !r.tier || !Number.isFinite(r.level));
if (missing.length) throw new Error(`Rows without tier or level: ${missing.map((r) => r.name).join(", ")}`);

// Item sprites: an image URL doesn't follow Wiki file redirects ("Coins.png" -> "Coins_10000.png"), so record
// the real file for every drop or log item whose File:<item>.png is a redirect. The page uses "<item>.png" otherwise.
const itemNames = new Set();
for (const r of records) {
  for (const rows of Object.values(r.drops)) for (const d of rows) itemNames.add(d.item);
  for (const u of [...r.uniques, ...(BOSS_GUIDES[r.id]?.uniques?.add ?? [])]) itemNames.add(u);
}
const sprites = await servedFiles([...itemNames].map((n) => fileName(`${n}.png`)));
const itemImages = Object.fromEntries(
  [...itemNames]
    .map((n) => [n, sprites.get(fileName(`${n}.png`))])
    .filter(([n, file]) => file && file !== fileName(`${n}.png`))
    .sort(([a], [b]) => a.localeCompare(b)),
);

const today = new Date().toISOString().slice(0, 10);
const source = `// Generated by scripts/import-bosses.mjs on ${today}. Do not edit by hand: rerun the script.
// Source: RuneScape Wiki (CC BY-NC-SA 3.0) — the Bosses page and each boss page.
import type { BossRecord } from "./bossTypes";

export const IMPORTED_BOSSES: BossRecord[] = ${JSON.stringify(records, null, 2)};

/** Drop and log items whose sprite file isn't "<item>.png" (a Wiki file redirect, resolved). */
export const BOSS_ITEM_IMAGES: Record<string, string> = ${JSON.stringify(itemImages, null, 2)};
`;
writeFileSync(OUT, source.replace(/\r?\n/g, "\r\n"));
console.log(review.join("\n"));
console.log(`Imported ${records.length} bosses; ${records.filter((r) => !r.members).length} free-to-play.`);
const texts = records.flatMap((r) => r.requirements.filter((q) => q.kind === "text").map((q) => `${r.name}: ${q.text}`));
console.log(`Text requirements (${texts.length}):\n  ${texts.join("\n  ")}`);
