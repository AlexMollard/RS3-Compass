// Types only: this module must not pull the generated Slayer data into the main chunk.
import type { TrainingSite } from "./data.ts";
import type { SkillName } from "./skillNames.ts";

export type TaskVerdict = {
  /** "prefer": worth a prefer slot or an extension; "block": spend a block on it; "skip": cancel it if you have points. */
  verdict: "prefer" | "do" | "skip" | "block";
  reason: string;
  /** Skills the task's drops feed, beyond Slayer and the combat XP itself. */
  feeds: SkillName[];
  /** Shown on regular-account profiles only, where a non-Ironman should act differently. */
  mainNote?: string;
  fastest: {
    where: string;
    site?: TrainingSite;
    style: "melee" | "ranged" | "magic" | "necromancy" | "any";
    aoe: boolean;
    notes: string;
  };
  checked: string;
  sources: string[];
};

export type MasterBlocks = {
  block: { task: string; reason: string }[];
  skip: { task: string; reason: string }[];
  checked: string;
  sources: string[];
};

