const option = (
  id: string,
  title: string,
  wiki: string,
  image: string,
  locations: string[],
  method: string,
  benefit: string,
  extra: Partial<TrainingOption> = {},
): TrainingOption => ({
  id,
  title,
  wiki,
  image,
  locations,
  method,
  benefit,
  supplies: recipeSupplies[id],
  ...extra,
  sites: sites[id],
});
const stage = (
  from: number,
  to: number,
  title: string,
  options: TrainingOption[],
  supplies: string[],
) => ({
  from,
  to,
  title,
  options,
  supplies,
});

